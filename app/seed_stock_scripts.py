    def insert_scripts_for_lang(lang_id, lang_code, lang_name, scenarios):
        inserted = 0
        cur_max_seq = c.execute("SELECT IFNULL(MAX(seq), 0) FROM scripts WHERE language_id=?", (lang_id,)).fetchone()[0]
        
        for idx, (dom, subdom, spec, abbr, scenario_title, turns_list) in enumerate(scenarios, 1):
            cur_max_seq += 1
            code = f"{lang_code}-{dom[:2].upper()}-{abbr}-{cur_max_seq:04d}"
            
            # Format turns
            turn_json = json.dumps([
                {"speaker": str(t_idx % 2 + 1), "role": speaker, "text": text}
                for t_idx, (speaker, text) in enumerate(turns_list)
            ], ensure_ascii=False)
            words = sum(len(text.split()) for _, text in turns_list)

            # Flexible attrs: diverse genders
            g_mode = idx % 3
            if g_mode == 0:
                attrs_gender = {"A": "M", "B": "F"}
            elif g_mode == 1:
                attrs_gender = {"A": "F", "B": "M"}
            else:
                attrs_gender = {"A": "", "B": ""}
                
            attrs_json = json.dumps({
                "genders": attrs_gender,
                "domain": dom,
                "subdomain": subdom,
                "specialisation": spec,
                "scenario": scenario_title,
                "language": lang_name
            }, ensure_ascii=False)

            brief = f"{scenario_title} - {lang_name} roleplay script in {dom} / {subdom}"
            
            c.execute("""
                INSERT INTO scripts(
                    language_id, seq, code, domain, subdomain, specialisation,
                    attrs, brief, status, version, words, is_test, source, created_at, updated_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, 'APPROVED', 1, ?, 0, 'approved_stock', ?, ?)
            """, (
                lang_id, cur_max_seq, code, dom, subdom, spec,
                attrs_json, brief, words, now, now
            ))
            sid = c.execute("SELECT last_insert_rowid()").fetchone()[0]
            
            c.execute("""
                INSERT OR REPLACE INTO script_versions(script_id, version, turns, words, created_at)
                VALUES (?, 1, ?, ?, ?)
            """, (sid, turn_json, words, now))
            inserted += 1

        con.commit()
        print(f"Successfully inserted {inserted} fresh APPROVED scripts for {lang_name} (ID {lang_id}).")
        return inserted

